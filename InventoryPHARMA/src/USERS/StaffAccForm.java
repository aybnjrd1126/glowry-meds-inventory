    private void AddUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddUserActionPerformed
        // TODO add your handling code here:
        
        JTextField userField = new JTextField();
        JPasswordField passField = new JPasswordField();

        Object[] message = {
            "New Staff Username:", userField,
            "Password:", passField
        };

        int option = JOptionPane.showConfirmDialog(this, message, "Add Staff Account", JOptionPane.OK_CANCEL_OPTION);

        if (option == JOptionPane.OK_OPTION) {
            String username = userField.getText().trim();
            String password = new String(passField.getPassword()).trim();

            if (username.isEmpty() || password.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill in all fields.");
                return;
            }

            if (userDAO.usernameExists(username)) {
                JOptionPane.showMessageDialog(this, "Username already taken.");
                return;
            }

            boolean created = userDAO.registerUser(username, password, "Staff");

            if (created) {
                JOptionPane.showMessageDialog(this, "Staff account created!");
                loadUserTable();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to create account.");
            }
        }
        
    }//GEN-LAST:event_AddUserActionPerformed

    private void ToggleBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ToggleBtnActionPerformed
        // TODO add your handling code here:
         int row = Usertbl.getSelectedRow();

        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Please select a staff account first.");
            ToggleBtn.setSelected(false);
            return;
        }

        String username = Usertbl.getValueAt(row, 0).toString();
        boolean makeActive = ToggleBtn.isSelected();

        int confirm = JOptionPane.showConfirmDialog(
            this,
            (makeActive ? "Activate" : "Deactivate") + " account: " + username + "?",
            "Confirm",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm == JOptionPane.YES_OPTION) {
            boolean success = userDAO.setUserActiveStatus(username, makeActive);
            if (success) {
                JOptionPane.showMessageDialog(this, "Account updated.");
                ToggleBtn.setText(makeActive ? "ACTIVE" : "INACTIVE");
                loadUserTable();
            } else {
                JOptionPane.showMessageDialog(this, "Update failed.");
            }
        } else {
            ToggleBtn.setSelected(!makeActive); // revert toggle if cancelled
        }
        
    }//GEN-LAST:event_ToggleBtnActionPerformed

