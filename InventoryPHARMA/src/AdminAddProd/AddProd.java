    private void ArchivedbttnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ArchivedbttnActionPerformed
        // TODO add your handling code here:
        String code = txtCode.getText().trim();

    if (code.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please select or enter a product code to be archive.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to archive product " + code + "?",
        "Confirm Archived",
        JOptionPane.YES_NO_OPTION
    );

    if (confirm == JOptionPane.YES_OPTION) {
        ProductDAO dao = new ProductDAO();
        boolean deleted = dao.archiveProduct(code);

        if (deleted) {
            JOptionPane.showMessageDialog(this, "Archived Product!");
            loadTableData();

            txtCode.setText("");
            txtMname.setText("");
            txtPrice.setText("");
            txtQty.setValue(0);
        } else {
            JOptionPane.showMessageDialog(this, "Archived failed — code not found?");
        }
    }
        
    }//GEN-LAST:event_ArchivedbttnActionPerformed

