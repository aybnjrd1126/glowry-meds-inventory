    private void printbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_printbtnActionPerformed
        if (medtbl.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "No items in the order yet.");
        return;
    }

    double totalCost;
    double pay;

    try {
        totalCost = Double.parseDouble(txttotal.getText());
        pay = Double.parseDouble(txtpayment.getText());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Enter a valid payment amount.");
        return;
    }

    if (pay < totalCost) {
        JOptionPane.showMessageDialog(this, "Payment is not enough.");
        return;
    }

    double balance = pay - totalCost;
    txtbal.setText(String.valueOf(balance));
    
    salesDAO.recordSale(totalCost, pay, balance);

    StaffTotalSales.setText("Today's Sales: " + salesDAO.getTotalSalesToday());

    
    DefaultTableModel model = (DefaultTableModel) medtbl.getModel();
    ReceiptForm receipt = new ReceiptForm(model, totalCost, pay, balance);
    receipt.setVisible(true);

    this.dispose();


    }//GEN-LAST:event_printbtnActionPerformed

    private void txtmedcKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtmedcKeyPressed
        // TODO add your handling code here:

        if (evt.getKeyCode() == KeyEvent.VK_ENTER) {
            String code = txtmedc.getText().trim();

            if (code.isEmpty()) {
                return;
            }

            Product p = productDAO.getProductByCode(code);

            if (p == null) {
                JOptionPane.showMessageDialog(this, "Med Code not Found");
            } else if (p.getQty() <= 0) {
                JOptionPane.showMessageDialog(this, "This product is out of stock.");
            } else {
                currentCode = p.getCode();
                txtmedn.setText(p.getProdname());
                txtprice.setText(String.valueOf(p.getPrice()));
                txtqty.requestFocus();
            }
        }
    }//GEN-LAST:event_txtmedcKeyPressed

