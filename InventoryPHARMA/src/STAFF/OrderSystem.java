    private void CategorytblMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CategorytblMouseClicked
        // TODO add your handling code here:
        int row = Categorytbl.getSelectedRow();
    if (row >= 0) {
        String code = Categorytbl.getValueAt(row, 0).toString();

        Product p = productDAO.getProductByCode(code);

        if (p == null) {
            JOptionPane.showMessageDialog(this, "Product not found.");
        } else if (p.getQty() <= 0) {
            JOptionPane.showMessageDialog(this, "This product is out of stock.");
        } else {
            currentCode = p.getCode();
            txtmedc.setText(p.getCode());
            txtmedn.setText(p.getProdname());
            txtprice.setText(String.valueOf(p.getPrice()));
            txtqty.requestFocus();
        }
    }
        
    }//GEN-LAST:event_CategorytblMouseClicked

    private void showCategory(String category) {
    List<Product> products = productDAO.getProductsByCategory(category);

    DefaultTableModel model = (DefaultTableModel) Categorytbl.getModel();
    model.setRowCount(0);

    for (Product p : products) {
        model.addRow(new Object[]{ p.getCode(), p.getProdname(), p.getPrice(), p.getQty() });
    }
}
    
