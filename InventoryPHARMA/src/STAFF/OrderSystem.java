    private void addbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addbtnActionPerformed
        // TODO add your handling code here:
        if (currentCode.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter a valid Med Code first.");
        return;
    }

    double price;
    int qty;

    try {
        price = Double.parseDouble(txtprice.getText());
        qty = (int) txtqty.getValue();
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid price or quantity.");
        return;
    }

    if (qty <= 0) {
        JOptionPane.showMessageDialog(this, "Quantity must be at least 1.");
        return;
    }

    Product current = productDAO.getProductByCode(currentCode);
    if (current == null || current.getQty() < qty) {
        JOptionPane.showMessageDialog(this, "Not enough stock available.");
        return;
    }

    double total = price * qty;

    df = (DefaultTableModel) medtbl.getModel();
    df.addRow(new Object[]{
        txtmedn.getText(),
        price,
        qty,
        total
    });

    productDAO.reduceStock(currentCode, qty);

    double sum = 0;
    for (int i = 0; i < medtbl.getRowCount(); i++) {
        sum += Double.parseDouble(medtbl.getValueAt(i, 3).toString());
    }
    txttotal.setText(String.valueOf(sum));

    currentCode = "";
    txtmedc.setText("");
    txtmedn.setText("");
    txtqty.setValue(0);
    txtprice.setText("");
    txtmedc.requestFocus();
    }//GEN-LAST:event_addbtnActionPerformed

