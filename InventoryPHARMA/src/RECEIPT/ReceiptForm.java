    private void buildReceipt(DefaultTableModel orderTable, double totalCost, double payment, double balance) {
        StringBuilder sb = new StringBuilder();

        sb.append("========================================\n");
        sb.append("           PHARMA INVENTORY\n");
        sb.append("              RECEIPT\n");
        sb.append("========================================\n\n");
         sb.append("Date: ").append(LocalDate.now()).append("\n\n");

        sb.append(String.format("%-15s %6s %6s %8s%n", "ITEM", "PRICE", "QTY", "TOTAL"));
        sb.append("----------------------------------------\n");

        for (int i = 0; i < orderTable.getRowCount(); i++) {
            String name = orderTable.getValueAt(i, 0).toString();
            String price = orderTable.getValueAt(i, 1).toString();
            String qty = orderTable.getValueAt(i, 2).toString();
            String total = orderTable.getValueAt(i, 3).toString();

            sb.append(String.format("%-15s %6s %6s %8s%n", name, price, qty, total));
        }

        sb.append("----------------------------------------\n");
        sb.append(String.format("%-27s %10.2f%n", "TOTAL:", totalCost));
        sb.append(String.format("%-27s %10.2f%n", "PAYMENT:", payment));
        sb.append(String.format("%-27s %10.2f%n", "CHANGE:", balance));
        sb.append("========================================\n");
        sb.append("         Thank you for your purchase!\n");

        txtArea.setText(sb.toString());
        txtArea.setFont(new java.awt.Font("Monospaced", java.awt.Font.PLAIN, 14));
    }
    
